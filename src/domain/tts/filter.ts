export function ttsExcludeTerms(value: string): string[] {
  // A textarea invites one term per line as well as comma lists.
  return [...new Set(value.split(/[,\n]/).map(term => term.trim()).filter(Boolean))];
}
export function hasTtsSpeech(text: string, skipChars = 1): boolean {
  let count = 0;
  for (const character of text) {
    const cp = character.codePointAt(0)!;
    let low = 0, high = TTS_IGNORED_RANGES.length - 1, ignored = false;
    while (low <= high) {
      const middle = (low + high) >>> 1, [start, end] = TTS_IGNORED_RANGES[middle];
      if (cp < start) high = middle - 1;
      else if (cp > end) low = middle + 1;
      else { ignored = true; break; }
    }
    if (!ignored && ++count > skipChars) return true;
  }
  return false;
}
export function allowedTtsText(text: string, terms: readonly string[], skipChars = 1): boolean {
  // Countdowns and timestamps ([00:10… 00:09…]) carry no word in any language.
  return hasTtsSpeech(text, skipChars) && /\p{L}/u.test(text) && !terms.some(term => text.includes(term));
}
/** `[00:00 - SHOOTING FINISHED]` is read as `00:00 - SHOOTING FINISHED`. */
export function ttsSpokenText(text: string, stripBrackets: boolean): string {
  return stripBrackets ? text.replace(/[[\]【】〔〕]/g, ' ').replace(/\s{2,}/g, ' ').trim() : text;
}
